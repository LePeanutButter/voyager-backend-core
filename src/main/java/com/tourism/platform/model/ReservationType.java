package com.tourism.platform.model;

/**
 * Enumeration for reservation types
 * 
 * Defines different categories of reservations that can be made
 * through the tourism platform.
 */
public enum ReservationType {
    /**
     * Hotel and accommodation reservations
     */
    HOTEL,
    
    /**
     * Flight and airline reservations
     */
    FLIGHT,
    
    /**
     * Car rental reservations
     */
    CAR_RENTAL,
    
    /**
     * Tour and excursion bookings
     */
    TOUR,
    
    /**
     * Restaurant reservations
     */
    RESTAURANT,
    
    /**
     * Event and entertainment tickets
     */
    EVENT,
    
    /**
     * Cruise bookings
     */
    CRUISE,
    
    /**
     * Train and railway reservations
     */
    TRAIN,
    
    /**
     * Bus transportation reservations
     */
    BUS,
    
    /**
     * Activity and experience bookings
     */
    ACTIVITY,
    
    /**
     * Spa and wellness reservations
     */
    SPA,
    
    /**
     * Other miscellaneous reservations
     */
    OTHER
}
