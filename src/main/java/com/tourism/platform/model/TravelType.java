package com.tourism.platform.model;

/**
 * Enumeration for travel types
 * 
 * Defines different categories of travel experiences
 * available in the tourism platform.
 */
public enum TravelType {
    /**
     * Leisure and vacation travel
     */
    LEISURE,
    
    /**
     * Business travel
     */
    BUSINESS,
    
    /**
     * Adventure and outdoor activities
     */
    ADVENTURE,
    
    /**
     * Cultural and heritage tourism
     */
    CULTURAL,
    
    /**
     * Educational and learning travel
     */
    EDUCATIONAL,
    
    /**
     * Medical and wellness tourism
     */
    MEDICAL,
    
    /**
     * Religious or spiritual travel
     */
    RELIGIOUS,
    
    /**
     * Romantic travel (honeymoon, anniversary)
     */
    ROMANTIC,
    
    /**
     * Family-oriented travel
     */
    FAMILY,
    
    /**
     * Solo travel
     */
    SOLO
}
