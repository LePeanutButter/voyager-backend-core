package com.tourism.platform.model;

/**
 * Enumeration for activity types in travel plans
 * 
 * Defines different categories of activities that can be included
 * in a travel itinerary.
 */
public enum ActivityType {
    /**
     * General sightseeing and exploration
     */
    SIGHTSEEING,
    
    /**
     * Cultural experiences and museum visits
     */
    CULTURAL,
    
    /**
     * Adventure and outdoor activities
     */
    ADVENTURE,
    
    /**
     * Dining and food experiences
     */
    DINING,
    
    /**
     * Shopping and retail therapy
     */
    SHOPPING,
    
    /**
     * Entertainment and nightlife
     */
    ENTERTAINMENT,
    
    /**
     * Sports and recreational activities
     */
    SPORTS,
    
    /**
     * Relaxation and wellness activities
     */
    RELAXATION,
    
    /**
     * Educational experiences
     */
    EDUCATIONAL,
    
    /**
     * Transportation between locations
     */
    TRANSPORTATION,
    
    /**
     * Accommodation-related activities
     */
    ACCOMMODATION,
    
    /**
     * Business meetings or conferences
     */
    BUSINESS,
    
    /**
     * Social events and gatherings
     */
    SOCIAL
}
